#!/usr/bin/env bash
# Render deploy/Caddyfile.live from deploy/.env (HTTP lab default, or TLS manual/ACME).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEPLOY_DIR="${MUSEHUB_DEPLOY_DIR:-$ROOT/deploy}"
ENV_FILE="${MUSEHUB_ENV_FILE:-$DEPLOY_DIR/.env}"
OUT="${DEPLOY_DIR}/Caddyfile.live"
UPSTREAM="${MUSEHUB_CADDY_UPSTREAM:-musehub-server:8080}"

[[ -f "$ENV_FILE" ]] && set -a && # shellcheck source=/dev/null
  source "$ENV_FILE" && set +a

tls_mode="${MUSEHUB_GATEWAY_TLS_MODE:-off}"
domain="${MUSEHUB_GATEWAY_TLS_DOMAIN:-}"
email="${MUSEHUB_ACME_EMAIL:-}"
cert="${MUSEHUB_TLS_CERT_FILE:-}"
key="${MUSEHUB_TLS_KEY_FILE:-}"
listen_port="${MUSEHUB_GATEWAY_HTTP_PORT:-8080}"

placeholder_domain() {
  [[ -z "$1" || "$1" == change-me* || "$1" == example.local ]]
}

site_handlers() {
  cat <<EOF
  encode gzip

  @api path /api /api/* /git /git/* /mcp /mcp/*
  handle @api {
    reverse_proxy ${UPSTREAM}
  }

  handle /healthz {
    reverse_proxy ${UPSTREAM}
  }

  handle /readyz {
    reverse_proxy ${UPSTREAM}
  }

  handle /version {
    reverse_proxy ${UPSTREAM}
  }

  handle {
    root * /srv/web
    try_files {path} /index.html
    file_server
  }
EOF
}

case "$tls_mode" in
  off)
    {
      echo "# Generated by render-gateway-caddyfile.sh (HTTP lab / default production install)."
      echo ":${listen_port} {"
      site_handlers
      echo "}"
    } >"$OUT"
    echo "render_gateway_caddyfile=ok mode=off path=$OUT"
    ;;
  manual)
    if placeholder_domain "$domain"; then
      echo "render_gateway_caddyfile=fail TLS manual requires MUSEHUB_GATEWAY_TLS_DOMAIN" >&2
      exit 1
    fi
    cert="${cert:-$DEPLOY_DIR/tls/cert.pem}"
    key="${key:-$DEPLOY_DIR/tls/key.pem}"
    if [[ ! -f "$cert" || ! -f "$key" ]]; then
      echo "render_gateway_caddyfile=fail missing cert/key (cert=$cert key=$key)" >&2
      exit 1
    fi
    {
      echo "# Generated by render-gateway-caddyfile.sh (TLS manual)."
      echo "{ admin off }"
      echo
      echo "${domain} {"
      echo "  tls /etc/musehub/tls/cert.pem /etc/musehub/tls/key.pem"
      site_handlers
      echo "}"
    } >"$OUT"
    echo "render_gateway_caddyfile=ok mode=manual domain=$domain path=$OUT"
    ;;
  acme)
    if placeholder_domain "$domain"; then
      echo "render_gateway_caddyfile=fail TLS acme requires MUSEHUB_GATEWAY_TLS_DOMAIN" >&2
      exit 1
    fi
    if [[ -z "$email" || "$email" == change-me* ]]; then
      echo "render_gateway_caddyfile=fail TLS acme requires MUSEHUB_ACME_EMAIL" >&2
      exit 1
    fi
    {
      echo "# Generated by render-gateway-caddyfile.sh (TLS ACME)."
      echo "{"
      echo "  admin off"
      echo "  email ${email}"
      echo "}"
      echo
      echo ":80 {"
      echo "  redir https://${domain}{uri} permanent"
      echo "}"
      echo
      echo "${domain} {"
      echo "  tls {"
      echo "    protocols tls1.2 tls1.3"
      echo "  }"
      site_handlers
      echo "}"
    } >"$OUT"
    echo "render_gateway_caddyfile=ok mode=acme domain=$domain path=$OUT"
    ;;
  *)
    echo "render_gateway_caddyfile=fail unknown MUSEHUB_GATEWAY_TLS_MODE=$tls_mode" >&2
    exit 1
    ;;
esac
